/**
 * @fileoverview Generates a table of held-item damage multipliers from
 * {@code @pkmn/dex} Gen 7 data, so the damage model can reflect the item a
 * Pokémon is holding. Each entry is a rule: { mult, type?, types?, category?,
 * users? } — the multiplier applies only when the move's type/category (and,
 * for signature items, the holder) match.
 *
 * Most item effects are coded as functions in the dex (not introspectable), so
 * we derive what we can structurally (Plates expose their type) and match the
 * rest against the stable shortDesc text, with a small curated set for the
 * items whose effect isn't a plain "<Type>-type attacks have 1.2x power".
 */

import fs from 'node:fs';
import path from 'node:path';
import { Dex } from '@pkmn/dex';

const OUT_PATH = path.resolve('src', 'generated', 'gen7ItemDamage.generated.js');

// Items whose damage effect isn't a simple type/Plate boost. The non-signature
// entries are verified against shortDesc at build time (assertions below).
const CURATED = {
  lifeorb: { mult: 1.3 },
  choiceband: { mult: 1.5, category: 'Physical' },
  choicespecs: { mult: 1.5, category: 'Special' },
  muscleband: { mult: 1.1, category: 'Physical' },
  wiseglasses: { mult: 1.1, category: 'Special' },
  // Signature items: only their listed holders get the boost.
  lightball: { mult: 2, users: ['pikachu'] },
  thickclub: { mult: 2, category: 'Physical', users: ['cubone', 'marowak', 'marowakalola'] },
  souldew: { mult: 1.2, types: ['Dragon', 'Psychic'], users: ['latios', 'latias'] },
};

function main() {
  const dex = Dex.forGen(7);
  const table = {};
  let derived = 0;

  for (const item of dex.items.all()) {
    if (!item.exists) continue;
    // Z-crystals expose onPlate (their Z-move type) but give no passive damage
    // boost — they enable a one-time Z-move. Skip them, and any future-gen
    // item.
    if (item.zMove || item.isZ || item.gen > 7) continue;
    const id = item.id;
    const desc = item.shortDesc || '';

    if (CURATED[id]) {
      table[id] = CURATED[id];
      continue;
    }
    // Plates expose their type structurally and give a 1.2x boost to it.
    if (item.onPlate) {
      table[id] = { mult: 1.2, type: item.onPlate };
      derived += 1;
      continue;
    }
    // Type-enhancing held items (Charcoal, Mystic Water, Silk Scarf, ...).
    let match = desc.match(/^Holder's (\w+)-type attacks have 1\.2x power/);
    if (match) {
      table[id] = { mult: 1.2, type: match[1] };
      derived += 1;
      continue;
    }
    // Type Gems: a single-use 1.3x boost to one type. Modeled as a persistent
    // type boost — it overstates sustained damage but reflects the opening hit
    // the item is bought for (and how heavily this app leans on Reborn's Gems).
    match = desc.match(
      /^Holder's first successful (\w+)-type attack will have 1\.3x/);
    if (match) {
      table[id] = { mult: 1.3, type: match[1] };
      derived += 1;
      continue;
    }
    // Everything else (Expert Belt's SE-only boost, Metronome's ramp, defensive
    // and utility items) is intentionally left out of the damage estimate.
  }

  const expect = (id, needle) => {
    const desc = dex.items.get(id).shortDesc || '';
    if (!desc.includes(needle)) {
      throw new Error(`Curated item ${id} no longer matches dex ("${needle}" not in "${desc}")`);
    }
  };
  expect('lifeorb', '1.3x damage');
  expect('choiceband', 'Attack is 1.5x');
  expect('choicespecs', 'Sp. Atk is 1.5x');
  expect('muscleband', 'physical attacks have 1.1x power');
  expect('wiseglasses', 'special attacks have 1.1x power');

  const body = `// Generated by scripts/build-item-damage.mjs from @pkmn/dex Gen 7 data.
// Do not edit by hand. Held-item damage multipliers keyed by item id; each rule
// is { mult, type?, types?, category?, users? } and applies only when the move's
// type/category (and holder, for signature items) match.

export const GEN7_ITEM_DAMAGE = ${JSON.stringify(table, null, 2)};
`;

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, body);
  console.log(
    `Wrote damage rules for ${Object.keys(table).length} items (${derived} derived, ${Object.keys(CURATED).length} curated).`,
  );
}

main();
