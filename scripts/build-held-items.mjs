// Builds the held-item universe used by the Team Builder inventory picker and
// item recommendations, derived from the per-Pokémon Smogon set data. Items are
// sorted by how broadly they're used (appearance count) so the most common ones
// surface first in the picker. Reproducible: re-run via `npm run build:held-items`.

import fs from "node:fs";
import path from "node:path";
import { TYPE_GEMS } from "../src/reborn/typeGems.js";
import { REBORN_SEEDS } from "../src/reborn/rebornSeeds.js";

const SET_INDEX_GLOB_ROOT = path.resolve("site-data", "data", "set-index");
const OUT_PATH = path.resolve(
  "src",
  "generated",
  "gen7HeldItems.generated.js",
);
const HIDDEN = new Set(["other", "nothing", ""]);

function toId(name) {
  return String(name || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "");
}

function* walkJsonFiles(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walkJsonFiles(full);
    else if (entry.isFile() && entry.name.endsWith(".json")) yield full;
  }
}

function main() {
  const byId = new Map();

  for (const file of walkJsonFiles(SET_INDEX_GLOB_ROOT)) {
    let data;
    try {
      data = JSON.parse(fs.readFileSync(file, "utf8"));
    } catch {
      continue;
    }

    for (const item of data.items || []) {
      const name = item.name;
      const id = toId(name);
      if (HIDDEN.has(id)) continue;

      const existing = byId.get(id);
      if (existing) {
        existing.appearances += 1;
        // Prefer a spaced display name over a squished one (e.g. "Bright Power").
        if (name.includes(" ") && !existing.name.includes(" ")) {
          existing.name = name;
        }
      } else {
        byId.set(id, { id, name, appearances: 1 });
      }
    }
  }

  const items = [...byId.values()]
    .sort(
      (a, b) => b.appearances - a.appearances || a.name.localeCompare(b.name),
    )
    .map(({ id, name }) => ({ id, name }));

  // Reborn-holdable items that don't appear in USUM Smogon data — the type Gems
  // and the Reborn Field Seeds. Appended so they're always selectable.
  for (const name of [...TYPE_GEMS.map((gem) => gem.gemName), ...REBORN_SEEDS]) {
    const id = toId(name);
    if (!byId.has(id)) items.push({ id, name });
  }

  const body = `// Generated by scripts/build-held-items.mjs from Smogon set data.
// Do not edit by hand. Sorted by how broadly each item is used.

export const GEN7_HELD_ITEMS = ${JSON.stringify(items, null, 2)};

export const GEN7_HELD_ITEMS_BY_ID = Object.fromEntries(
  GEN7_HELD_ITEMS.map((item) => [item.id, item]),
);
`;

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, body);
  console.log(`Wrote ${items.length} held items to ${OUT_PATH}`);
}

main();
