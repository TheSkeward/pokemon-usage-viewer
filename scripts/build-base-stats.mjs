// Generates per-species base stats (Atk/Def/SpA/SpD/Spe) from @pkmn/dex Gen 7
// data, used by the Team Builder's stat-fit seed model. Stored as compact
// [atk, def, spa, spd, spe] arrays keyed by species id.
//
// Also emits GEN7_BASE_STAT_TOTALS (full base-stat total, *including* HP) keyed
// by species id, used by the form-readiness discount to gauge how much weaker a
// stuck pre-evolution is than the evolved form it borrows its usage prior from.
// HP stays out of the [Atk..Spe] array (the seed model indexes it positionally)
// but is folded into the totals, since HP is central to walls like the Chansey
// line.

import fs from "node:fs";
import path from "node:path";
import { Dex } from "@pkmn/dex";

const OUT_PATH = path.resolve("src", "generated", "gen7BaseStats.generated.js");
const STATS = ["atk", "def", "spa", "spd", "spe"];

function main() {
  const dex = Dex.forGen(7);
  const map = {};
  const totals = {};
  const hp = {};

  const weights = {};

  for (const species of dex.species.all()) {
    if (!species.exists || species.gen > 7 || !species.baseStats) continue;
    map[species.id] = STATS.map((k) => species.baseStats[k]);
    hp[species.id] = species.baseStats.hp || 0;
    totals[species.id] =
      (species.baseStats.hp || 0) +
      STATS.reduce((sum, k) => sum + (species.baseStats[k] || 0), 0);
    // Weight in kg, for the variable-power damage formulas (Grass Knot /
    // Low Kick read the target's weight; Heavy Slam / Heat Crash the ratio).
    weights[species.id] = species.weightkg || 0;
  }

  const body = `// Generated by scripts/build-base-stats.mjs from @pkmn/dex Gen 7 data.
// Do not edit by hand. Base stats per species as [Atk, Def, SpA, SpD, Spe].

export const GEN7_BASE_STATS = ${JSON.stringify(map)};

// Full base-stat total (including HP) per species id.
export const GEN7_BASE_STAT_TOTALS = ${JSON.stringify(totals)};

// Base HP per species id (kept out of the positional array above, which the
// stat-fit seed model indexes as [Atk..Spe]). Used by display-layer stat
// tooltips that need the full six-stat line.
export const GEN7_BASE_HP = ${JSON.stringify(hp)};

// Weight in kg per species id, for weight-scaled move power (Grass Knot,
// Low Kick, Heavy Slam, Heat Crash).
export const GEN7_WEIGHTS_KG = ${JSON.stringify(weights)};
`;

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, body);
  console.log(
    `Wrote base stats + totals for ${Object.keys(map).length} species.`,
  );
}

main();
