/**
 * @fileoverview Generates the set of Gen 7 species that can have the Unburden
 * ability, used to weight consumable held items (gems, berries) higher for
 * them: Unburden doubles Speed when the held item is consumed, and a Z-Crystal
 * (which our gem proxy is built on) does NOT trigger it, so the proxy
 * under-rates gems here.
 */

import fs from 'node:fs';
import path from 'node:path';
import { Dex } from '@pkmn/dex';

const OUT_PATH = path.resolve(
  'src',
  'generated',
  'gen7UnburdenSpecies.generated.js',
);

function main() {
  const dex = Dex.forGen(7);

  const ids = dex.species
    .all()
    .filter(
      (species) =>
        species.exists &&
        species.gen >= 1 &&
        species.gen <= 7 &&
        !species.isNonstandard &&
        Object.values(species.abilities || {}).includes('Unburden'),
    )
    .map((species) => species.id)
    .sort();

  const map = Object.fromEntries(ids.map((id) => [id, true]));

  const body = `// Generated by scripts/build-unburden-species.mjs from @pkmn/dex Gen 7 data.
// Do not edit by hand. Species (by id) that can have the Unburden ability.

export const GEN7_UNBURDEN_SPECIES = ${JSON.stringify(map, null, 2)};
`;

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, body);
  console.log(`Wrote ${ids.length} Unburden species to ${OUT_PATH}`);
  console.log(ids.join(', '));
}

main();
